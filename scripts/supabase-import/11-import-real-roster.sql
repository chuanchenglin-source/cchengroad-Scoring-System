DECLARE
    v_dup_count BIGINT;
BEGIN
    SELECT COUNT(*) INTO v_dup_count FROM (
        SELECT squad_id, name
          FROM members
         GROUP BY squad_id, name
        HAVING COUNT(*) > 1
    ) AS dups;

    IF v_dup_count > 0 THEN
